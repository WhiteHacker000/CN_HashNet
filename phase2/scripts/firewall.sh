#!/usr/bin/env bash
# Extension C — Service isolation with macOS pf (packet filter).
# Run on the BACKEND machines: Mac 3 (Backend A) and Mac 4 (Backend B).
#
#   firewall.sh render A|B [--with-standby]   print the ruleset (no changes)
#   firewall.sh apply  A|B [--with-standby]   back up current pf state, load rules, enable pf
#   firewall.sh status                        show loaded rules + per-rule packet counters
#   firewall.sh rollback                      restore Apple's /etc/pf.conf and our pf enable ref
#
# Default policy: ONLY the primary edge (Mac 2) may open TCP connections to the
# backend port. Everyone else is silently dropped (client sees a timeout).
# --with-standby also allows the standby edge (Mac 4) — needed for Extension E.
#
# Nothing here edits /etc/pf.conf, so rollback is always: reload /etc/pf.conf.
set -eu
. "$(dirname "$0")/common.sh"

FW_DIR="$REPO_ROOT/firewall"
BACKUP_ROOT="$FW_DIR/backups"
TOKEN_FILE="$BACKUP_ROOT/pf-enable-token"

render() {
    which="$1"; standby="$2"
    case "$which" in
        A|a) port="$BACKEND_A_PORT"; name="Backend A (Mac 3)" ;;
        B|b) port="$BACKEND_B_PORT"; name="Backend B (Mac 4)" ;;
        *) die "backend must be A or B" ;;
    esac
    allowed="$EDGE_PRIMARY_IP"
    label="primary edge only"
    if [ "$standby" = "yes" ]; then allowed="$EDGE_PRIMARY_IP, $EDGE_STANDBY_IP"; label="primary + standby edge"; fi
    cat <<EOF
# =============================================================================
# Team 1 — Extension C service isolation — $name, TCP port $port
# Allowed sources: $label
# Generated by phase2/scripts/firewall.sh from phase2/team.env
# Rollback: sudo pfctl -f /etc/pf.conf   (or: firewall.sh rollback)
# =============================================================================

# ---- Tables ----
table <team1_edges> const { $allowed }

# ---- Options ----
# Never filter loopback: lets a process on this Mac reach its own backend
# (e.g. the standby nginx on Mac 4 -> Backend B on the same Mac).
set skip on lo0

# ---- Apple default anchors (copied from /etc/pf.conf so AirDrop, sharing,
#      the app firewall, etc. keep working while our rules are loaded) ----
scrub-anchor "com.apple/*"
nat-anchor "com.apple/*"
rdr-anchor "com.apple/*"
dummynet-anchor "com.apple/*"
anchor "com.apple/*"

# ---- Service isolation ----
# 'quick' = stop evaluating at the first matching rule, so order matters:
# 1) the edge(s) may open connections to the backend port
pass  in quick inet proto tcp from <team1_edges> to any port $port flags S/SA keep state
# 2) any other host trying the backend port is dropped (no RST is sent, so
#    the client waits and times out; 'block return' would give "refused")
block drop in quick inet proto tcp from any to any port $port

load anchor "com.apple" from "/etc/pf.anchors/com.apple"
EOF
}

parse_args() {
    WHICH="${1:-}"; STANDBY="no"
    [ "${2:-}" = "--with-standby" ] && STANDBY="yes"
    [ -n "$WHICH" ] || die "usage: firewall.sh $CMD A|B [--with-standby]"
}

CMD="${1:-}"; shift || true
case "$CMD" in
render)
    parse_args "$@"; render "$WHICH" "$STANDBY"
    ;;
apply)
    need_macos; parse_args "$@"
    mkdir -p "$BACKUP_ROOT"
    stamp="$(date '+%Y%m%d-%H%M%S')"
    bdir="$BACKUP_ROOT/$stamp"; mkdir -p "$bdir"
    info "Backing up current pf state to firewall/backups/$stamp/"
    cp /etc/pf.conf "$bdir/etc-pf.conf"
    # shellcheck disable=SC2024  # redirect into a user-owned backup file is intended
    sudo pfctl -sr   > "$bdir/rules-before.txt" 2>/dev/null || true
    # shellcheck disable=SC2024
    sudo pfctl -s info > "$bdir/info-before.txt" 2>/dev/null || true
    rules="$bdir/team1-backend-$WHICH.pf.conf"
    render "$WHICH" "$STANDBY" > "$rules"
    cp "$rules" "$FW_DIR/active-ruleset.pf.conf"
    info "Syntax check"; run sudo pfctl -nf "$rules"
    info "Loading rules"; run sudo pfctl -f "$rules"
    # -E enables pf and returns a reference token; rollback releases exactly
    # this reference, so pf stays as it was if something else had enabled it.
    token="$(sudo pfctl -E 2>&1 | awk '/[Tt]oken/{print $NF}')"
    [ -n "$token" ] && echo "$token" > "$TOKEN_FILE"
    ok "Backend $WHICH isolated. Allowed: $( [ "$STANDBY" = yes ] && echo "$EDGE_PRIMARY_IP, $EDGE_STANDBY_IP" || echo "$EDGE_PRIMARY_IP") (pf token ${token:-?})"
    info "Prove it:  from Mac 2 -> nc -vz -G 3 <this-ip> <port>  (succeeds)"
    info "           from Mac 1 -> nc -vz -G 3 <this-ip> <port>  (times out)"
    info "Undo with: ./phase2/scripts/firewall.sh rollback"
    ;;
status)
    need_macos
    run sudo pfctl -s info | head -3
    run sudo pfctl -vsr
    ;;
rollback)
    need_macos
    info "Restoring Apple default ruleset from /etc/pf.conf"
    run sudo pfctl -f /etc/pf.conf
    if [ -f "$TOKEN_FILE" ]; then
        run sudo pfctl -X "$(cat "$TOKEN_FILE")" || true
        rm -f "$TOKEN_FILE"
    fi
    rm -f "$FW_DIR/active-ruleset.pf.conf"
    sudo pfctl -s info | head -1
    ok "Firewall rolled back. Backups of every apply are kept in firewall/backups/"
    ;;
*) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
